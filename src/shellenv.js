'use strict';
// Make KF_* secrets available in every shell Claude Code spawns, without touching the
// user's dotfiles and without relying on hook timing. The vault regenerates
// ~/.keyfence/env.sh on every write. Two env vars, set only for the Claude Code
// process via settings.json `env`, make its shells source that file:
//
//   zsh : ZDOTDIR=~/.keyfence/zdot. Every file zsh may read (.zshenv, .zprofile,
//         .zshrc, .zlogin, .zlogout) chains to the user's real one, and .zshenv adds
//         the guarded source line. Interactive `!` shells keep their normal config.
//   bash: BASH_ENV=~/.keyfence/bashenv.sh, read by non-interactive bash. Chains to a
//         pre-existing BASH_ENV, then the guarded line.
//
// The guard `[ -n "$CLAUDECODE" ]` keeps secrets out of any shell that is not a Claude
// Code child even if someone exports these variables elsewhere.
const fs = require('fs');
const os = require('os');
const path = require('path');
const { paths, ensureHome } = require('./paths');

const ZSH_FILES = ['.zshenv', '.zprofile', '.zshrc', '.zlogin', '.zlogout'];

function shellQuote(s) { return `'${String(s).replace(/'/g, `'\\''`)}'`; }

function guardLine(envsh = paths.envsh) {
  return `[ -n "$CLAUDECODE" ] && [ -r ${shellQuote(envsh)} ] && . ${shellQuote(envsh)}`;
}

function chainLine(file) { return `[ -r ${shellQuote(file)} ] && . ${shellQuote(file)}`; }

function zdotPath() { return path.join(paths.home, 'zdot'); }
function bashShimPath() { return path.join(paths.home, 'bashenv.sh'); }

// previousZdot: the user's own ZDOTDIR if they had one (else $HOME).
function writeZdot(previousZdot, envsh = paths.envsh) {
  ensureHome();
  const dir = zdotPath();
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  const real = previousZdot && path.resolve(previousZdot) !== path.resolve(dir) ? previousZdot : os.homedir();
  for (const name of ZSH_FILES) {
    const lines = [`# keyfence: chains to ${path.join(real, name)}; do not edit (regenerated by keyfence install)`, chainLine(path.join(real, name))];
    if (name === '.zshenv') lines.push(guardLine(envsh), 'true');
    fs.writeFileSync(path.join(dir, name), lines.join('\n') + '\n', { mode: 0o600 });
  }
  return dir;
}

function writeBashShim(previousBashEnv, envsh = paths.envsh) {
  ensureHome();
  const lines = ['# keyfence: BASH_ENV shim for non-interactive bash (Claude Code Bash tool)'];
  if (previousBashEnv && path.resolve(previousBashEnv) !== path.resolve(bashShimPath())) lines.push(chainLine(previousBashEnv));
  lines.push(guardLine(envsh), 'true');
  fs.writeFileSync(bashShimPath(), lines.join('\n') + '\n', { mode: 0o600 });
  return bashShimPath();
}

module.exports = { guardLine, writeZdot, writeBashShim, zdotPath, bashShimPath, ZSH_FILES };
